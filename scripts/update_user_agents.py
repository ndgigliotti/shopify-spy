"""Regenerate shopify_spy/_user_agents.py from the browser vendors' release feeds.

Run before a release: uv run python scripts/update_user_agents.py

Browsers freeze most of their user agent (OS tokens, minor versions), so only
major versions change. They come from official sources:

- Chrome: Google's Version History API (two newest stable majors per platform)
- Firefox: Mozilla's product-details (latest release and ESR)
- Edge: Microsoft's Edge update API (newest stable major)
- Safari: no machine-readable feed; SAFARI_VERSION is updated by hand from
  Apple's release notes (https://developer.apple.com/documentation/safari-release-notes)

The strings themselves are templates. Before writing, the script compares their
format (major versions masked) with an informal list of real-world user agents,
which is how a vendor's format change gets noticed.

Exit status: 0 when the file is current or was updated (stdout says which;
NOTICE lines need a human look but don't block), 2 when a template no longer
matches real browsers or a string's version tokens disagree (WARNING lines;
nothing is written).
"""

from __future__ import annotations

import ast
import datetime
import json
import re
import sys
import urllib.request
from pathlib import Path

# major.minor, as Safari always sends it (jnrbsn's list drops the ".0"; a bare
# "Version/27" matches no real browser)
SAFARI_VERSION = "27.0"

OUTPUT = Path(__file__).resolve().parent.parent / "shopify_spy" / "_user_agents.py"
CHROME_API = (
    "https://versionhistory.googleapis.com/v1/chrome/platforms/{platform}/channels/stable/"
    "versions?order_by=version%20desc&pageSize=50"
)
FIREFOX_API = "https://product-details.mozilla.org/1.0/firefox_versions.json"
EDGE_API = "https://edgeupdates.microsoft.com/api/products"
# Informal list of current real-world user agents, used only to detect format changes
REFERENCE_LIST = "https://jnrbsn.github.io/user-agents/user-agents.json"
# Mask major versions only: frozen parts like Chrome's ".0.0.0" are part of the format.
# Safari's Version/ has a real minor version, so it's masked whole.
VERSION_RE = re.compile(r"(Chrome/|Edg/|Firefox/|rv:)\d+|(Version/)[\d.]+")
SAFARI_RE = re.compile(r"Version/(\d+)")

# Frozen platform tokens, as each browser sends them whatever the real OS version
CHROME = {
    "Windows": "Windows NT 10.0; Win64; x64",
    "macOS": "Macintosh; Intel Mac OS X 10_15_7",
    "Linux": "X11; Linux x86_64",
}
CHROME_PLATFORM_IDS = {"Windows": "win", "macOS": "mac", "Linux": "linux"}
FIREFOX = {
    "Windows": ["Windows NT 10.0; Win64; x64"],
    "macOS": ["Macintosh; Intel Mac OS X 10.15"],
    "Linux": ["X11; Linux x86_64", "X11; Ubuntu; Linux x86_64"],
}


def get_json(url: str) -> object:
    with urllib.request.urlopen(url, timeout=30) as response:
        return json.load(response)


def major(version: str) -> int:
    return int(version.split(".")[0])


def chrome_majors(platform_id: str) -> list[int]:
    data = get_json(CHROME_API.format(platform=platform_id))
    majors = sorted({major(v["version"]) for v in data["versions"]}, reverse=True)
    return sorted(majors[:2])


def firefox_majors() -> list[int]:
    data = get_json(FIREFOX_API)
    return sorted({major(data["FIREFOX_ESR"]), major(data["LATEST_FIREFOX_VERSION"])})


def edge_major() -> int:
    products = get_json(EDGE_API)
    stable = next(p for p in products if p["Product"] == "Stable")
    return max(major(r["ProductVersion"]) for r in stable["Releases"] if r["Platform"] == "Windows")


def build() -> list[tuple[str, list[str]]]:
    """(comment, user agents) groups, in the order the module lists them."""
    webkit = "AppleWebKit/537.36 (KHTML, like Gecko)"
    groups = []
    for name, token in CHROME.items():
        agents = [
            f"Mozilla/5.0 ({token}) {webkit} Chrome/{m}.0.0.0 Safari/537.36"
            for m in chrome_majors(CHROME_PLATFORM_IDS[name])
        ]
        groups.append((f"Chrome - {name}", agents))
    ff = firefox_majors()
    for name, tokens in FIREFOX.items():
        agents = [
            f"Mozilla/5.0 ({token}; rv:{m}.0) Gecko/20100101 Firefox/{m}.0"
            for token in tokens
            for m in ff
        ]
        groups.append((f"Firefox - {name}", agents))
    safari = (
        f"Mozilla/5.0 ({CHROME['macOS']}) AppleWebKit/605.1.15 (KHTML, like Gecko) "
        f"Version/{SAFARI_VERSION} Safari/605.1.15"
    )
    groups.append(("Safari - macOS", [safari]))
    e = edge_major()
    chromium = f"Mozilla/5.0 ({CHROME['Windows']}) {webkit} Chrome/{e}.0.0.0 Safari/537.36"
    edge = f"{chromium} Edg/{e}.0.0.0"
    groups.append(("Edge - Windows", [edge]))
    return groups


def render(groups: list[tuple[str, list[str]]]) -> str:
    today = datetime.date.today().isoformat()
    lines = [
        '"""Browser user agent strings for request spoofing.',
        "",
        "Generated by scripts/update_user_agents.py from the browser vendors' release",
        f"feeds ({today}); rerun it before a release instead of editing by hand.",
        '"""',
        "",
        "# fmt: off",
        "USER_AGENTS = [",
    ]
    for comment, agents in groups:
        lines.append(f"    # {comment}")
        lines.extend(f'    "{agent}",' for agent in agents)
    lines += ["]", "# fmt: on", ""]
    return "\n".join(lines)


def shape(agent: str) -> str:
    """The user agent with major versions replaced, leaving only its format."""
    return VERSION_RE.sub(lambda m: f"{m.group(1) or m.group(2)}N", agent)


def safari_major(agents: list[str]) -> int | None:
    versions = [
        int(m.group(1))
        for a in agents
        if "Safari/" in a and "Chrome/" not in a and (m := SAFARI_RE.search(a))
    ]
    return max(versions, default=None)


def consistency_errors(agents: list[str]) -> list[str]:
    """Tokens a real browser always sends together; a mismatch is an easy fake-UA tell.

    Checked here rather than against the reference list, which itself drops
    Safari's minor version.
    """
    errors = []
    for a in agents:
        chrome = re.search(r"Chrome/([\d.]+) Safari/537\.36", a)
        if "Chrome/" in a and not (chrome and re.fullmatch(r"\d+\.0\.0\.0", chrome.group(1))):
            errors.append(f"Chrome not in reduced 'Chrome/N.0.0.0 Safari/537.36' form: {a}")
        if "Edg/" in a:
            edge = re.search(r"Edg/(\d+)\.0\.0\.0$", a)
            if not (edge and chrome and chrome.group(1).split(".")[0] == edge.group(1)):
                errors.append(f"Edge major doesn't match its Chrome major: {a}")
        if "Firefox/" in a:
            rv, ff = re.search(r"rv:([\d.]+)\)", a), re.search(r"Firefox/([\d.]+)$", a)
            if not (rv and ff and rv.group(1) == ff.group(1)):
                errors.append(f"Firefox rv: doesn't equal its Firefox/ version: {a}")
        # major.minor, sometimes with a patch (Version/26.0, Version/26.6.1); never bare
        if "Version/" in a and not re.search(r"Version/\d+\.\d+(\.\d+)? Safari/", a):
            errors.append(f"Safari Version/ isn't major.minor: {a}")
    return errors


def check_format(agents: list[str], reference: list[str]) -> tuple[list[str], list[str]]:
    """Compare our formats with real-world ones: (warnings, notices).

    A warning means one of our templates no longer appears among real browsers'
    user agents (a vendor changed its format), so the new list shouldn't be used.
    Notices need a look but don't block: a format only the reference has (e.g. a
    browser we don't template) or a newer Safari than SAFARI_VERSION.
    """
    ours = {shape(a) for a in agents}
    theirs = {shape(a) for a in reference}
    warnings = [
        f"WARNING format no longer seen in real browsers: {s}" for s in sorted(ours - theirs)
    ]
    notices = [f"NOTICE format we don't generate: {s}" for s in sorted(theirs - ours)]
    their_safari, our_safari = safari_major(reference), safari_major(agents)
    if their_safari and our_safari and their_safari > our_safari:
        notices.append(f"NOTICE Safari {their_safari} is out; update SAFARI_VERSION ({our_safari})")
    return warnings, notices


def current_agents() -> list[str] | None:
    """USER_AGENTS as the module lists it now (parsed, not imported)."""
    try:
        tree = ast.parse(OUTPUT.read_text())
    except (OSError, SyntaxError):
        return None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "USER_AGENTS" for t in node.targets
        ):
            return ast.literal_eval(node.value)
    return None


def main() -> int:
    groups = build()
    agents = [agent for _, group in groups for agent in group]
    try:
        reference = [a for a in get_json(REFERENCE_LIST) if isinstance(a, str)]
    except Exception as exc:  # advisory: the official feeds alone still give a valid list
        print(f"NOTICE format check skipped: {REFERENCE_LIST}: {exc}")
        warnings, notices = [], []
    else:
        warnings, notices = check_format(agents, reference)
        if not warnings and not notices:
            print(f"Format check: every format matches {REFERENCE_LIST}")
    warnings += [f"WARNING {e}" for e in consistency_errors(agents)]
    for line in [*warnings, *notices]:
        print(line)
    if warnings:
        print(f"Not writing {OUTPUT}: fix the templates in this script first")
        return 2
    # Leave the file (and its date) alone unless the list changed, so a clean
    # git diff means there's nothing to update
    if agents == current_agents():
        print(f"Unchanged: {OUTPUT}")
    else:
        OUTPUT.write_text(render(groups))
        print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
